// 1. DYNAMIC CATEGORY CLASSIFIER
export function classifyIslamicQuery(message: string): IslamicCategory {
  const q = message.toLowerCase().trim();
  const rawQ = message.trim();

  // Wellbeing / Hal Chaal ("kia hal he", "kese ho", "how are you", "کیا حال ہے", "کیسے ہو")
  if (
    q.includes("kia hal") ||
    q.includes("kya hal") ||
    q.includes("kese ho") ||
    q.includes("kaisay ho") ||
    q.includes("kaise ho") ||
    q.includes("how are you") ||
    q.includes("theek ho") ||
    rawQ.includes("کیا حال") ||
    rawQ.includes("کیسے ہو") ||
    rawQ.includes("کیسے ہیں") ||
    rawQ.includes("طبیعت کیسی") ||
    rawQ.includes("خیریت")
  ) {
    return "wellbeing";
  }

  // Gratitude / Shukriya
  if (
    q.includes("shukriya") ||
    q.includes("jazakallah") ||
    q.includes("jazak allah") ||
    q.includes("thanks") ||
    q.includes("thank you") ||
    rawQ.includes("شکریہ") ||
    rawQ.includes("جزاک اللہ") ||
    rawQ.includes("مہربانی")
  ) {
    return "gratitude";
  }

  // Pure Greetings / Salaam
  if (
    q.includes("salam") ||
    q.includes("asslam") ||
    q.includes("assalam") ||
    q.includes("slaam") ||
    rawQ.includes("سلام") ||
    rawQ.includes("السلام علیکم") ||
    rawQ.includes("اسلام علیکم") ||
    rawQ.includes("وعلیکم") ||
    q === "hi" ||
    q === "hello"
  ) {
    return "greeting";
  }

  // Identity / About ("ap kn", "kon ho", "who are you", "aap kon hain")
  if (
    q === "ap kn" ||
    q === "aap kn" ||
    q.includes("ap kon") ||
    q.includes("aap kon") ||
    q.includes("who are you") ||
    q.includes("kon ho") ||
    q.includes("kaun ho") ||
    q.includes("koun ho") ||
    rawQ.includes("کون ہو") ||
    rawQ.includes("کون ہیں") ||
    rawQ.includes("کیا ہو") ||
    rawQ.includes("تعارف")
  ) {
    return "identity";
  }

  // Tajweed
  if (
    q.includes("tajweed") ||
    q.includes("makhraj") ||
    q.includes("makharaj") ||
    q.includes("ikhfa") ||
    q.includes("idgham") ||
    q.includes("izhar") ||
    q.includes("iqlab") ||
    q.includes("noon sakin") ||
    q.includes("meem sakin") ||
    rawQ.includes("تجوید") ||
    rawQ.includes("مخرج") ||
    rawQ.includes("مخارج") ||
    rawQ.includes("اخفاء") ||
    rawQ.includes("ادغام") ||
    rawQ.includes("اظہار") ||
    rawQ.includes("اقلاب") ||
    rawQ.includes("نون ساکن") ||
    rawQ.includes("تنوین") ||
    rawQ.includes("مد کے قواعد") ||
    rawQ.includes("قلقلہ")
  ) {
    return "tajweed";
  }

  // Hadith (Check before general words)
  if (
    q.includes("bukhari") ||
    q.includes("muslim") ||
    q.includes("tirmidhi") ||
    q.includes("abu dawud") ||
    q.includes("hadith") ||
    q.includes("hadees") ||
    rawQ.includes("بخاری") ||
    rawQ.includes("مسلم") ||
    rawQ.includes("ترمذی") ||
    rawQ.includes("ابو داؤد") ||
    rawQ.includes("حدیث") ||
    rawQ.includes("احادیث") ||
    rawQ.includes("روایت")
  ) {
    return "hadith";
  }

  // Fatwa
  if (
    q.includes("fatwa") ||
    q.includes("darulifta") ||
    q.includes("mufti") ||
    rawQ.includes("فتویٰ") ||
    rawQ.includes("فتوی") ||
    rawQ.includes("دارالافتاء") ||
    rawQ.includes("دار الافتاء") ||
    rawQ.includes("مفتی") ||
    rawQ.includes("علماء سے فتویٰ")
  ) {
    return "fatwa";
  }

  // Fiqh & Ibadat (Namaz, Roza, Zakat, Hajj, Taharat, Nikah, etc.)
  if (
    q.includes("namaz") ||
    q.includes("salah") ||
    q.includes("roza") ||
    q.includes("fasting") ||
    q.includes("ramadan") ||
    q.includes("zakat") ||
    q.includes("hajj") ||
    q.includes("wudu") ||
    q.includes("ghusl") ||
    q.includes("nikah") ||
    q.includes("talaq") ||
    q.includes("qasr") ||
    q.includes("safar") ||
    q.includes("sajda") ||
    rawQ.includes("نماز") ||
    rawQ.includes("روزہ") ||
    rawQ.includes("رمضان") ||
    rawQ.includes("زکوٰۃ") ||
    rawQ.includes("زکوۃ") ||
    rawQ.includes("حج") ||
    rawQ.includes("عمرہ") ||
    rawQ.includes("وضو") ||
    rawQ.includes("غسل") ||
    rawQ.includes("نکاح") ||
    rawQ.includes("طلاق") ||
    rawQ.includes("قصر") ||
    rawQ.includes("سفر") ||
    rawQ.includes("سجدہ سہو") ||
    rawQ.includes("مسئلہ") ||
    rawQ.includes("کھانے") ||
    rawQ.includes("پینے") ||
    rawQ.includes("فرائض") ||
    rawQ.includes("واجب")
  ) {
    return "fiqh";
  }

  // Hifz
  if (
    q.includes("hifz") ||
    q.includes("memoriz") ||
    rawQ.includes("حفظ") ||
    rawQ.includes("حفاظ") ||
    rawQ.includes("منزل دہرانا") ||
    rawQ.includes("سبقی") ||
    rawQ.includes("متشابہات") ||
    rawQ.includes("قرآن یاد")
  ) {
    return "hifz";
  }

  // Tafseer
  if (
    q.includes("tafseer") ||
    q.includes("tafsir") ||
    q.includes("ibn kathir") ||
    rawQ.includes("تفسیر") ||
    rawQ.includes("ابن کثیر") ||
    rawQ.includes("شان نزول")
  ) {
    return "tafseer";
  }

  // Quran
  if (
    q.includes("quran") ||
    q.includes("surah") ||
    q.includes("ayah") ||
    q.includes("ayat") ||
    rawQ.includes("قرآن") ||
    rawQ.includes("سورت") ||
    rawQ.includes("سورۃ") ||
    rawQ.includes("آیت") ||
    rawQ.includes("بقرہ")
  ) {
    return "quran";
  }

  // Dua / Azkar
  if (
    q.includes("dua") ||
    q.includes("azkar") ||
    q.includes("tasbeeh") ||
    rawQ.includes("دعا") ||
    rawQ.includes("اذکار") ||
    rawQ.includes("تسبیح") ||
    rawQ.includes("وظیفہ")
  ) {
    return "dua_azkar";
  }

  // Seerah & History
  if (
    q.includes("seerah") ||
    q.includes("prophet") ||
    q.includes("sahaba") ||
    q.includes("history") ||
    rawQ.includes("سیرت") ||
    rawQ.includes("صحابہ") ||
    rawQ.includes("غزوہ") ||
    rawQ.includes("تاریخ")
  ) {
    return "seerah";
  }

  return "general_islamic";
}

